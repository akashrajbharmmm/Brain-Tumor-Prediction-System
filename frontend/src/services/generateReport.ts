import jsPDF from 'jspdf';

interface ReportData {
  id: number;
  prediction: string;
  tumorType: string | null;
  confidence: number;
  createdAt: string;
  originalImageUrl: string;
  heatmapImageUrl: string | null;
}

async function loadImageAsDataUrl(url: string): Promise<string> {
  const token = localStorage.getItem('token');
  const res = await fetch(url, {
    headers: token ? { Authorization: `Bearer ${token}` } : {},
  });
  const blob = await res.blob();
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onloadend = () => resolve(reader.result as string);
    reader.onerror = reject;
    reader.readAsDataURL(blob);
  });
}

export async function generateReport(data: ReportData) {
  const doc = new jsPDF();

  doc.setFontSize(18);
  doc.text('Brain Tumor Prediction Report', 14, 20);

  doc.setFontSize(10);
  doc.setTextColor(100);
  doc.text('Educational use only — not a diagnostic device', 14, 27);

  doc.setDrawColor(220);
  doc.line(14, 32, 196, 32);

  doc.setFontSize(11);
  doc.setTextColor(0);
  let y = 42;

  doc.text(`Scan ID: #${data.id}`, 14, y);
  y += 7;
  doc.text(`Date: ${new Date(data.createdAt).toLocaleString()}`, 14, y);
  y += 7;
  doc.text(`Prediction: ${data.prediction}`, 14, y);
  y += 7;
  if (data.tumorType) {
    doc.text(`Tumor Type: ${data.tumorType}`, 14, y);
    y += 7;
  }
  doc.text(`Confidence: ${(data.confidence * 100).toFixed(2)}%`, 14, y);
  y += 12;

  try {
    const originalDataUrl = await loadImageAsDataUrl(data.originalImageUrl);
    doc.text('Original MRI', 14, y);
    doc.addImage(originalDataUrl, 'JPEG', 14, y + 4, 80, 80);
  } catch {
    doc.text('Original MRI image unavailable', 14, y);
  }

  if (data.heatmapImageUrl) {
    try {
      const heatmapDataUrl = await loadImageAsDataUrl(data.heatmapImageUrl);
      doc.text('Grad-CAM Heatmap', 105, y);
      doc.addImage(heatmapDataUrl, 'JPEG', 105, y + 4, 80, 80);
    } catch {
      doc.text('Heatmap unavailable', 105, y);
    }
  }

  y += 92;
  doc.setFontSize(9);
  doc.setTextColor(150);
  doc.text(
    'This report is generated by an automated model for educational purposes only.',
    14,
    y
  );
  doc.text('It should not be used as a substitute for professional medical diagnosis.', 14, y + 5);

  doc.save(`scan-report-${data.id}.pdf`);
}